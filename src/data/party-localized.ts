const TRANSLATIONS: Record<TranslatedLocale, Record<string, string>> = { fr: FR, zh: ZH }

export function hasPartyTranslation(locale: string, value: string): boolean {
	return (locale === 'fr' || locale === 'zh') && Object.hasOwn(TRANSLATIONS[locale], value)
}

function translate(locale: string, value: string): string {
	if (locale !== 'fr' && locale !== 'zh') return value
	return TRANSLATIONS[locale][value] ?? value
}

function localizePackageGroups(locale: string): PackageGroup[] {
	return PACKAGE_GROUPS.map((group) => ({
		...group,
		label: translate(locale, group.label),
		catered: localizeVariant(locale, group.catered),
		rentalOnly: localizeVariant(locale, group.rentalOnly),
	}))
}

function localizeVariant(locale: string, variant: PackageGroup['catered']): PackageGroup['catered'] {
	return {
		...variant,
		description: translate(locale, variant.description),
		serviceFee: translate(locale, variant.serviceFee),
		extraTime: variant.extraTime ? translate(locale, variant.extraTime) : undefined,
		addOns: variant.addOns?.map((item) => translate(locale, item)),
		packages: variant.packages.map((partyPackage) => ({
			...partyPackage,
			name: translate(locale, partyPackage.name),
			tier: translate(locale, partyPackage.tier),
			capacity: translate(locale, partyPackage.capacity),
			includes: partyPackage.includes.map((item) => translate(locale, item)),
		})),
	}
}

function localizeDetails<T extends { name: string; level: string; summary: string; details: Record<string, PackageDetailCell> }>(
	locale: string,
	details: readonly T[],
): T[] {
	return details.map((partyPackage) => ({
		...partyPackage,
		name: translate(locale, partyPackage.name),
		level: translate(locale, partyPackage.level),
		summary: translate(locale, partyPackage.summary),
		details: Object.fromEntries(
			Object.entries(partyPackage.details).map(([key, cell]) => [
				key,
				{
					selection: translate(locale, cell.selection),
					items: cell.items.map((item) => translate(locale, item)),
				},
			]),
		),
	})) as T[]
}

export function getLocalizedPartyContent(locale: string) {
	return {
		packageGroups: localizePackageGroups(locale),
		partyProcess: PARTY_PROCESS.map((step) => ({ title: translate(locale, step.title), body: translate(locale, step.body) })),
		partyPolicies: PARTY_POLICIES.map((policy) => ({ title: translate(locale, policy.title), items: policy.items.map((item) => translate(locale, item)) })),
		privateRoomDetailRows: PRIVATE_ROOM_DETAIL_ROWS.map((row) => ({ ...row, label: translate(locale, row.label) })),
		privateRoomPackageDetails: localizeDetails<PrivateRoomPackageDetail>(locale, PRIVATE_ROOM_PACKAGE_DETAILS),
		fullSpaceDetailRows: FULL_SPACE_DETAIL_ROWS.map((row) => ({ ...row, label: translate(locale, row.label) })),
		fullSpacePackageDetails: localizeDetails<FullSpacePackageDetail>(locale, FULL_SPACE_PACKAGE_DETAILS),
	}
}
